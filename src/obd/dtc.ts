// Diagnostic trouble codes (the "Check Engine" errors).
import { responseMessages } from './parse';

const LETTERS = ['P', 'C', 'B', 'U'];

/** Two raw bytes -> code like "P0171". Returns null for the empty 0000 slot. */
export function decodeDtc(a: number, b: number): string | null {
  if (a === 0 && b === 0) return null;
  const letter = LETTERS[(a & 0xc0) >> 6];
  const d1 = (a & 0x30) >> 4;
  const rest = (((a & 0x0f) << 8) | b).toString(16).toUpperCase().padStart(3, '0');
  return `${letter}${d1}${rest}`;
}

/**
 * Parse the reply to mode 03 (stored) or 07 (pending) or 0A (permanent).
 * On CAN cars the byte after the mode is a count of codes; on older
 * K-line cars there is no count and the reply is padded with zeros.
 */
export function parseDtcReply(raw: string, responseMode: number, isCan: boolean): string[] {
  const codes = new Set<string>();
  for (const msg of responseMessages(raw)) {
    if (msg[0] !== responseMode) continue;
    const start = isCan ? 2 : 1;
    for (let i = start; i + 1 < msg.length; i += 2) {
      const code = decodeDtc(msg[i], msg[i + 1]);
      if (code) codes.add(code);
    }
  }
  return [...codes];
}

