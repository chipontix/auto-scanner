const GROUPS: [RegExp, string][] = [
  [/^P0[0-1]/, 'Топливо и воздух'],
  [/^P02/, 'Топливо: форсунки'],
  [/^P03/, 'Зажигание, пропуски'],
  [/^P04/, 'Выхлоп и экология'],
  [/^P05/, 'Скорость и холостой ход'],
  [/^P06/, 'Блок управления'],
  [/^P07|^P08|^P09/, 'Коробка передач'],
  [/^P[123]/, 'Код производителя (двигатель)'],
  [/^C/, 'Шасси (ABS, подвеска)'],
  [/^B/, 'Кузов (подушки, климат, свет)'],
  [/^U/, 'Связь между блоками'],
];

export function describeDtc(code: string): string {
  if (KNOWN[code]) return KNOWN[code];
  const group = GROUPS.find(([re]) => re.test(code));
  return group ? `${group[1]}: описание зависит от марки` : 'Неизвестный код';
}
